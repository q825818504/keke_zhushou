const {chromium}=require('../desktop/node_modules/playwright');
const {spawn}=require('node:child_process');
const path=require('node:path');
const fs=require('node:fs');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
(async()=>{
 const server=spawn(path.join(root,'.venv-ocr/Scripts/python.exe'),[path.join(root,'scripts/check_native_equipment_browser_server.py')],{cwd:root,windowsHide:true});
 let browser;
 try{
  const port=await new Promise((resolve,reject)=>{let text='';server.stdout.on('data',part=>{text+=part.toString();if(text.includes('\n'))try{resolve(JSON.parse(text.split('\n')[0]).port)}catch(e){reject(e)}});server.stderr.on('data',p=>process.stderr.write(p));server.on('exit',c=>reject(Error('Fixture exited '+c)));});
  browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1380,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const status=()=>page.evaluate(async()=>await(await fetch('/inventory/status')).json());
  await page.goto('http://127.0.0.1:'+port);
  assert.equal(await page.locator('[data-native-assembly-reference]').count(),0);
  await page.evaluate(()=>{window.__sharedSolverCalls=0;const fn=DriveLayoutSolver.placementsFor;DriveLayoutSolver.placementsFor=(...args)=>{window.__sharedSolverCalls++;return fn(...args);};});
  await page.locator('[data-user-route="vision"]').click();
  const panel=page.locator('#userVisionRoute');
  await page.waitForFunction(()=>document.querySelector('[data-equipment="inspect"]')?.disabled===false);
  await panel.locator('#equipmentMode').selectOption('assembly');
  await panel.locator('[data-equipment="inspect"]').click();
  await panel.locator('#assemblyCharacter').waitFor();
  await panel.locator('#assemblyCharacter').selectOption('1003');
  const tape=await panel.locator('#assemblyCore option').filter({hasText:'#4'}).getAttribute('value');
  const drive=await panel.locator('[data-assembly-slot="0"] option').filter({hasText:'#3'}).getAttribute('value');
  await panel.locator('#assemblyCore').selectOption(tape);
  await panel.locator('[data-assembly-slot="0"]').selectOption(drive);
  await panel.locator('[data-assembly-add]').click();
  await panel.locator('[data-assembly-slot="1"]').selectOption(drive);
  await panel.locator('[data-equipment="assemble-preview"]').click();
  await page.waitForFunction(()=>document.querySelector('#equipmentStatus').textContent.includes('不能重复选择'));
  assert.equal((await status()).fixture_dispatch_count,0);
  await panel.locator('[data-assembly-remove="1"]').click();
  await panel.locator('#assemblyPlacement').selectOption('manual');
  await panel.locator('[data-assembly-coordinate="row"]').fill('5');
  await panel.locator('[data-assembly-coordinate="row"]').dispatchEvent('change');
  await panel.locator('[data-assembly-coordinate="column"]').fill('5');
  await panel.locator('[data-assembly-coordinate="column"]').dispatchEvent('change');
  await panel.locator('[data-equipment="assemble-preview"]').click();
  await page.waitForFunction(()=>document.querySelector('#equipmentStatus').textContent.includes('越出'));
  assert.equal((await status()).fixture_dispatch_count,0);
  await panel.locator('#assemblyPlacement').selectOption('auto');
  await panel.locator('[data-equipment="assemble-preview"]').click();
  await panel.locator('.equipment-preview h3').waitFor();
  assert.ok(await page.evaluate(()=>window.__sharedSolverCalls>0));
  assert.match(await panel.locator('.equipment-preview').textContent(),/从其他角色转移 1 件/);
  assert.equal(await panel.locator('.assembly-cell.is-filled').count(),2);
  assert.equal(await panel.locator('.assembly-operations li').count(),5);
  assert.equal((await status()).fixture_dispatch_count,0);
  const shots=path.join(root,'.planning/2026-10-16-native-equipment/artifacts');fs.mkdirSync(shots,{recursive:true});
  await panel.locator('.equipment-preview').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(shots,'assembly-desktop.png')});
  await page.setViewportSize({width:900,height:1000});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await panel.locator('.equipment-preview').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(shots,'assembly-900.png')});
  await panel.locator('#visionAccount').fill('独立装配测试');
  assert.equal(await panel.locator('.equipment-preview').count(),0);
  await panel.locator('[data-equipment="assemble-preview"]').click();
  await panel.locator('[data-equipment="start"]').waitFor();
  const expectedSteps=await panel.locator('.assembly-operations li').count();
  assert.equal(expectedSteps,5);
  await panel.locator('[data-equipment="start"]').click();
  await page.waitForFunction(async()=>{const s=await(await fetch('/inventory/status')).json();return s.equipment_job.state==='verified';});
  const final=await status();assert.equal(final.fixture_dispatch_count,expectedSteps);assert.equal(final.equipment_job.completed,expectedSteps);
  await page.waitForFunction(()=>document.querySelector('#equipmentStatus').textContent.includes('装配完成'));
  assert.deepEqual(errors,[]);
  console.log('Independent native assembly browser passed: shared solver, duplicate prevention, manual bounds, full preview, transfers, label invalidation, serial verified execution, 1380/900 widths; no character-catalog linkage.');
 }finally{if(browser)await browser.close();server.kill();}
})().catch(e=>{console.error(e);process.exitCode=1;});
