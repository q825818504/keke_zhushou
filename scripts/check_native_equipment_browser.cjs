const {chromium}=require('../desktop/node_modules/playwright');
const {spawn}=require('node:child_process');
const path=require('node:path');
const fs=require('node:fs');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
(async()=>{
 const server=spawn(path.join(root,'.venv-ocr/Scripts/python.exe'),[path.join(root,'scripts/check_native_equipment_browser_server.py')],{cwd:root,windowsHide:true});
 let browser;
 try {
  const port=await new Promise((resolve,reject)=>{let text='';server.stdout.on('data',part=>{text+=part.toString();if(text.includes('\n'))try{resolve(JSON.parse(text.split('\n')[0]).port)}catch(e){reject(e)}});server.stderr.on('data',part=>process.stderr.write(part));server.on('exit',code=>reject(Error('Fixture exited '+code)));});
  browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1380,height:950}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const status=()=>page.evaluate(async()=>await (await fetch('/inventory/status')).json());
  await page.goto('http://127.0.0.1:'+port);
  await page.locator('[data-user-route="vision"]').click();
  const panel=page.locator('#userVisionRoute');
  await panel.locator('[data-equipment="inspect"]').waitFor();
  await page.waitForFunction(()=>!document.querySelector('[data-equipment="inspect"]').disabled);
  await panel.locator('[data-equipment="inspect"]').click();
  await panel.locator('#equipmentCharacter').waitFor();
  assert.equal((await status()).fixture_dispatch_count,0);
  assert.equal(await panel.locator('[data-equipment="preview"]').isDisabled(),true);
  await panel.locator('#equipmentCharacter').selectOption('1003');
  await panel.locator('[data-equipment-category="drive"]').uncheck();
  await panel.locator('[data-equipment="preview"]').click();
  await panel.locator('.equipment-preview h3').waitFor();
  assert.match(await panel.locator('.equipment-preview h3').textContent(),/1 件/);
  assert.equal((await status()).fixture_dispatch_count,0);
  assert.equal(await panel.locator('.equipment-preview script').count(),0);
  await panel.locator('#visionAccount').fill('UI测试');
  assert.equal(await panel.locator('.equipment-preview').count(),0);
  await panel.locator('[data-equipment="preview"]').click();
  await panel.locator('.equipment-preview h3').waitFor();
  const screenshots=path.join(root,'.planning/2026-10-16-native-equipment/artifacts');
  fs.mkdirSync(screenshots,{recursive:true});
  await panel.locator('#equipmentHeading').scrollIntoViewIfNeeded();
  await panel.locator('section[aria-labelledby="equipmentHeading"]').screenshot({path:path.join(screenshots,'unequip-desktop.png')});
  await page.setViewportSize({width:900,height:950});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await panel.locator('section[aria-labelledby="equipmentHeading"]').screenshot({path:path.join(screenshots,'unequip-900.png')});
  await panel.locator('[data-equipment="start"]').click();
  await page.waitForFunction(async()=>{const s=await (await fetch('/inventory/status')).json();return s.equipment_job.state==='verified';});
  await page.waitForFunction(()=>document.querySelector('#equipmentStatus').textContent.includes('全部操作已由新库存快照确认'));
  const result=await status();
  assert.equal(result.fixture_dispatch_count,1);
  assert.equal(result.equipment_job.completed,1);
  assert.equal(await panel.locator('.equipment-preview').count(),0);
  await panel.locator('[data-equipment="inspect"]').click();
  await panel.locator('#equipmentCharacter').waitFor();
  await panel.locator('#equipmentCharacter').selectOption('1003');
  await panel.locator('[data-equipment="preview"]').click();
  await page.waitForFunction(()=>document.querySelector('.equipment-preview h3')?.textContent.includes('0 件'));
  assert.equal(await panel.locator('[data-equipment="start"]').count(),0);
  await page.route('**/inventory/equipment/inspect',route=>route.fulfill({status:400,contentType:'application/json',body:JSON.stringify({error:'接口未就绪 <script>fixture</script>'})}));
  await panel.locator('[data-equipment="inspect"]').click();
  await page.waitForFunction(()=>document.querySelector('#equipmentStatus').textContent.includes('接口未就绪'));
  assert.equal(await panel.locator('#equipmentStatus script').count(),0);
  assert.equal(await panel.locator('#equipmentCharacter').count(),0);
  assert.deepEqual(errors,[]);
  console.log('Native equipment browser checks passed: read-only inspect/preview, explicit confirmation, label invalidation, category/owner selection, verified result, zero-item empty state, escaped errors, 1380/900 widths.');
 } finally {if(browser)await browser.close();server.kill();}
})().catch(error=>{console.error(error);process.exitCode=1;});
