const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const html = fs.readFileSync(path.join(root, "index.html"), "utf8");
const storage = new Map();
const sandbox = { window: {}, localStorage: { getItem: key => storage.get(key) || null, setItem: (key, value) => storage.set(key, value) }, Event: class {}, };
sandbox.window.dispatchEvent = () => {};
vm.createContext(sandbox);
for (const [, file] of html.matchAll(/<script\s+src="([^"]+)"/g)) {
  if (file !== "app.js" && file !== "team_manager.js") vm.runInContext(fs.readFileSync(path.join(root, file), "utf8"), sandbox);
}
const manager = fs.readFileSync(path.join(root, "team_manager.js"), "utf8");
const storeCode = manager.slice(0, manager.indexOf("let guideDraft"));
vm.runInContext(storeCode, sandbox);
const store = sandbox.window.teamGuideStore;
const original = JSON.stringify(sandbox.window.teamTemplateKnowledge);
const seed = store.all()[0];
const edited = JSON.parse(JSON.stringify(seed));
edited.source_archetype = "编辑后的阵容";
edited.editorial.notes = "出场顺序与养成要求";
store.save(edited);
assert.equal(store.all().find(t => t.id === seed.id).source_archetype, edited.source_archetype);
assert.equal(JSON.stringify(sandbox.window.teamTemplateKnowledge), original, "source snapshots stay untouched");
const custom = { ...edited, id: "local-test", source_visibility: "local_editor" };
store.save(custom);
assert.equal(store.all().length, 28);
vm.runInContext(storeCode, sandbox);
assert.equal(sandbox.window.teamGuideStore.all().length, 28, "reload restores persisted edits");
const current = sandbox.window.teamGuideStore;
current.remove(custom.id);
assert.equal(current.all().length, 27);
current.save(custom);
assert.equal(current.all().length, 28, "undo restores deleted record");
assert.throws(() => current.save({ ...custom, member_character_ids: [seed.member_character_ids[0], seed.member_character_ids[0], seed.member_character_ids[1], seed.member_character_ids[2]] }));
assert.throws(() => current.import({ teams: [custom, custom] }));
const before = JSON.stringify(current.export());
assert.throws(() => current.import({ teams: [custom, { ...custom, id: "invalid", member_character_ids: ["unknown"] }] }));
assert.equal(JSON.stringify(current.export()), before, "invalid imports never partially modify records");
// Persisted guide edits feed the exact user recommendation entry point.
const app = fs.readFileSync(path.join(root, "app.js"), "utf8");
vm.runInContext(app.slice(0, app.indexOf("const userTeamSavedState")), sandbox);
vm.runInContext(app.slice(app.indexOf("const userTeamElementRing"), app.indexOf("function notify(")), sandbox);
vm.runInContext('const userTeamNameById = Object.fromEntries(Object.entries(characterData).map(([name, data]) => [data.id, name])); let userTeamOwnedNames = new Set(Object.keys(characterData)); let userTeamInvestmentByCharacterId = {};', sandbox);
vm.runInContext(app.slice(app.indexOf("function userTeamRoleKind("), app.indexOf("function userTeamMemberCard(")), sandbox);
current.remove(seed.id);
custom.source_order = -1;
current.save(custom);
const names = custom.member_character_ids.map(id => sandbox.window.characterKnowledge[id]?.name || Object.values(sandbox.window.characterKnowledge).find(c => c.id === id).name);
const plan = sandbox.userTeamBuildPlans(names[0]).find(p => p.id === custom.id);
assert.ok(plan, "saved custom guide is available to the user solver");
current.save({ ...custom, editorial: { ...custom.editorial, active: false } });
assert.ok(!sandbox.userTeamBuildPlans(names[0]).some(p => p.id === custom.id), "disabled guides are excluded");
assert.ok(!app.includes("userTeamGoal"), "preferences removed from runtime");
console.log("Guide checks passed: edit/create, reload, delete/undo, atomic imports, provenance, solver integration and disable.");
